"""The generational self-training loop.

Indexing convention (used everywhere in the outputs -- do not change it silently):
    model_0            = the base model, untouched
    metrics[g]         = measured ON model_g
    model_{g+1}        = SFT(model_g, data generated BY model_g)

So "calibration degrades at generation 2" means: the model produced by two rounds
of self-training is miscalibrated, and the data that made it came from model_1.

The loop is resumable: each generation writes a done-marker, and re-running skips
completed generations. An overnight grid that dies at g3 keeps g0-g2.
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import numpy as np

from .data.prep import build_pools, save_pools
from .eval.calibration import accuracy_by_bucket, calibration_report
from .eval.diversity import diversity_report
from .eval.grade import grade_all
from .eval.ivd import internal_verbal_divergence
from .eval.probes import probe_report
from .filters import apply_filter, build_sft_mix, expand_prompts, fresh_real_slice, sweep_threshold
from .markers.extract import lexicon_report
from .modeling.generate import generate_batch, score_choices, self_consistency
from .modeling.loader import load_model, load_tokenizer, model_param_count
from .modeling.train_sft import build_pairs, prune_checkpoint, train_sft
from .utils import (LOG, code_fingerprint, cuda_mem_summary, free_vram, pbar,
                    read_json, set_seed, stale, write_json, write_jsonl)

POP_BINS = [0, 100, 1000, 10000, 100000, 10**9]   # PopQA popularity -> tail buckets


class SelfTrainingLoop:
    def __init__(self, cfg, offline: bool = False):
        self.cfg = cfg
        self.offline = offline
        self.run_dir = Path(cfg.out_dir) / cfg.run_name
        self.run_dir.mkdir(parents=True, exist_ok=True)
        set_seed(cfg.seed)

    # ------------------------------------------------------------------ setup
    def prepare(self) -> dict:
        pools_dir = self.run_dir / "pools"
        marker = pools_dir / "_done.json"
        if marker.exists() and not stale(read_json(marker), "pools"):
            LOG.info("reusing pools in %s", pools_dir)
            from .utils import read_jsonl
            pools = {}
            for f in pools_dir.glob("*.jsonl"):
                name = f.stem.replace("eval_", "eval:")
                pools[name] = read_jsonl(f)
            return pools

        pools = build_pools(self.cfg, offline=self.offline)
        save_pools(pools, pools_dir)
        write_json(marker, {"ok": True, "code_fingerprint": code_fingerprint(),
                            "sizes": {k: len(v) for k, v in pools.items()}})
        return pools

    def gen_dir(self, g: int) -> Path:
        d = self.run_dir / f"gen{g}"
        d.mkdir(parents=True, exist_ok=True)
        return d

    def ckpt_dir(self, g: int) -> Path:
        return self.run_dir / "ckpt" / f"model_{g}"

    def model_source(self, g: int):
        """-> (base_model_name, adapter_path|None) for model_g.

        chain="weights"  : checkpoints are standalone merged models, so model_g
                           loads directly and the next generation trains on top.
        chain="data_only": checkpoints are adapters over the pristine base.
        """
        if g == 0:
            return self.cfg.model.name, None
        ck = self.ckpt_dir(g)
        from .manifest import checkpoint_usable
        ok, why = checkpoint_usable(ck)
        if not ok:
            raise FileNotFoundError(
                f"model_{g} is not loadable at {ck}: {why}. "
                f"Set loop.keep_checkpoints=true and rerun the chain from a "
                f"generation whose weights still exist.")
        if self.cfg.loop.chain == "data_only" and self.cfg.train.mode == "lora":
            return self.cfg.model.name, ck
        return str(ck), None

    # ------------------------------------------------------------- evaluation
    def evaluate_generation(self, g: int, pools: dict) -> dict:
        gd = self.gen_dir(g)
        done = gd / "_metrics.json"
        if done.exists():
            cached = read_json(done)
            if not stale(cached, f"gen{g} metrics"):
                LOG.info("gen %d already evaluated -- skipping", g)
                return cached

        cfg = self.cfg
        base, adapter = self.model_source(g)
        LOG.info("=== generation %d: evaluating %s (adapter=%s) ===", g, base, adapter)

        tok = load_tokenizer(base, cfg.model.trust_remote_code)
        model = load_model(base, dtype=cfg.model.dtype, attn_impl=cfg.model.attn_impl,
                           trust_remote_code=cfg.model.trust_remote_code,
                           device=cfg.device, adapter_path=adapter)

        t0 = time.time()
        metrics: dict = {
            "generation": g,
            "run_name": cfg.run_name,
            "lang": cfg.data.lang,
            "ratio": cfg.loop.ratio,
            "filter": cfg.loop.filter,
            "train_loss": cfg.train.loss,
            "model": {"base": base, "adapter": str(adapter) if adapter else None,
                      "params_b": round(model_param_count(model), 3)},
            "lexicon": lexicon_report(cfg.data.lang),
            "code_fingerprint": code_fingerprint(),
            "eval": {},
        }

        gen_kw = dict(style=cfg.gen.prompt_style, max_new_tokens=cfg.gen.max_new_tokens,
                      temperature=cfg.gen.temperature, top_p=cfg.gen.top_p,
                      do_sample=cfg.gen.do_sample, batch_size=cfg.gen.batch_size,
                      max_len=cfg.model.max_len, seed=cfg.gen.seed + g)

        # ---- held-out eval sets: this is where the paper's numbers come from --
        eval_keys = [k for k in pools if k.startswith("eval:")]
        for key in pbar(eval_keys, desc=f"gen{g} eval sets", total=len(eval_keys),
                        unit="set"):
            items = pools[key]
            name = key.split(":", 1)[1]
            recs = generate_batch(model, tok, items, **gen_kw)
            graded = grade_all(recs, lang=cfg.data.lang)

            # MCQ: also score option letters directly -- an exact p_correct beats
            # one parsed from a sampled string.
            if items and items[0].get("task_type") == "mcq":
                scored = score_choices(model, tok, items, style=cfg.gen.prompt_style,
                                       batch_size=max(1, cfg.gen.batch_size // 2),
                                       max_len=cfg.model.max_len)
                by_uid = {s["uid"]: s for s in scored}
                for r in graded:
                    s = by_uid.get(r["uid"])
                    if s:
                        # p_pred = confidence in the CHOSEN option (proper
                        # calibration target). p_correct = mass on the gold
                        # option, which is circular against correct_scored.
                        r["p_pred"] = s["p_pred"]
                        r["p_correct"] = s["p_correct"]
                        r["choice_probs"] = s["choice_probs"]
                        r["choice_logits"] = s.get("choice_logits")
                        r["choice_logits_raw"] = s.get("choice_logits_raw")
                        # FORMAT-INDEPENDENT correctness. Free-text matching
                        # scores a model near zero when it merely fails to emit
                        # a parseable option, so a self-training loop that only
                        # learns output FORMAT looks like a huge accuracy gain
                        # and masks (or inverts) real collapse. Letter scoring
                        # asks the model to rank the options directly, so it is
                        # unaffected by how chatty the generation is.
                        r["pred_idx_scored"] = s["pred_idx"]
                        r["correct_scored"] = int(s["correct"] or 0)
                        r["correct"] = r["correct_scored"]

            if cfg.gen.sc_samples > 1:
                sc = self_consistency(model, tok, items[: min(len(items), 300)],
                                      n_samples=cfg.gen.sc_samples,
                                      temperature=cfg.gen.sc_temperature,
                                      style=cfg.gen.prompt_style,
                                      max_new_tokens=cfg.gen.max_new_tokens,
                                      top_p=cfg.gen.top_p,
                                      batch_size=cfg.gen.batch_size,
                                      max_len=cfg.model.max_len, seed=cfg.gen.seed + g)
                for r in graded:
                    if r["uid"] in sc:
                        r.update(sc[r["uid"]])

            write_jsonl(gd / f"eval_{name}.jsonl", graded)

            entry = calibration_report(graded, n_boot=200, seed=cfg.seed)
            entry["diversity"] = diversity_report(graded)
            entry["popularity_buckets"] = accuracy_by_bucket(graded, "s_pop", POP_BINS)

            # ---- probes + IVD on held-out data (H3) ----------------------
            pr = probe_report(model, tok, graded, cfg)
            entry["probe"] = {k: v for k, v in pr.items() if k != "oof_scores"}
            entry["ivd"] = internal_verbal_divergence(graded, probe_res=pr)
            entry["ivd_tokenprob"] = internal_verbal_divergence(graded, probe_res=None)

            # ---- filter quality at this generation (H4) ------------------
            entry["filter_sweep"] = sweep_threshold(graded, "mean_token_prob")
            entry["filter_sweep_marker"] = sweep_threshold(graded, "marker_conf")

            metrics["eval"][name] = entry
            LOG.info("gen %d | %-14s acc %.3f | hedge %.3f | %s",
                     g, name, entry["accuracy"], entry["hedge_rate"],
                     _fmt_sig(entry))
            free_vram()

        metrics["eval_seconds"] = round(time.time() - t0, 1)
        metrics["vram"] = cuda_mem_summary()
        write_json(done, metrics)

        del model, tok
        free_vram()
        return metrics

    # --------------------------------------------------------------- training
    def train_next(self, g: int, pools: dict) -> dict:
        """Generate SFT data with model_g, train model_{g+1}."""
        cfg = self.cfg
        gd = self.gen_dir(g)
        ck = self.ckpt_dir(g + 1)
        if (ck / "_done.json").exists():
            cached = read_json(ck / "_done.json")
            if not stale(cached, f"model_{g + 1} checkpoint"):
                LOG.info("model_%d already trained -- skipping", g + 1)
                return cached
            # Do NOT reuse it. The checkpoint was trained on synthetic data
            # produced by the old code, so keeping it would propagate the very
            # artefact the code change fixed. Fall through and retrain.
            LOG.warning("model_%d was trained by different code -- retraining", g + 1)

        base, adapter = self.model_source(g)
        tok = load_tokenizer(base, cfg.model.trust_remote_code)
        model = load_model(base, dtype=cfg.model.dtype, attn_impl=cfg.model.attn_impl,
                           trust_remote_code=cfg.model.trust_remote_code,
                           device=cfg.device, adapter_path=adapter)

        prompt_pool = expand_prompts(pools["prompt_pool"], cfg.loop.samples_per_prompt)
        LOG.info("=== generation %d -> %d: generating %d synthetic SFT items ===",
                 g, g + 1, len(prompt_pool))
        recs = generate_batch(model, tok, prompt_pool,
                              style=cfg.gen.prompt_style,
                              max_new_tokens=cfg.gen.max_new_tokens,
                              temperature=cfg.gen.temperature, top_p=cfg.gen.top_p,
                              do_sample=cfg.gen.do_sample,
                              batch_size=cfg.gen.batch_size,
                              max_len=cfg.model.max_len, seed=cfg.gen.seed + 977 * g,
                              sampler=cfg.gen.sampler)
        graded = grade_all(recs, lang=cfg.data.lang)
        write_jsonl(gd / "synthetic.jsonl", graded)

        del model, tok
        free_vram()

        # Early-warning signal: entropy of the targets this round will train on.
        ents = [r["mean_entropy"] for r in graded if r.get("mean_entropy") is not None]
        self_target_entropy = float(np.mean(ents)) if ents else None

        kept, fq = apply_filter(graded, kind=cfg.loop.filter,
                                threshold=cfg.loop.filter_threshold)
        real_pool, fresh_slice = pools.get("real_pool", []), None
        if cfg.loop.real_fresh and cfg.loop.ratio < 1.0:
            n_real = cfg.loop.sft_size - int(round(cfg.loop.sft_size * cfg.loop.ratio))
            real_pool, fresh_slice = fresh_real_slice(real_pool, n_real, g, seed=cfg.seed)
        syn_sel, real_sel, mix_info = build_sft_mix(
            kept, real_pool, ratio=cfg.loop.ratio,
            total=cfg.loop.sft_size, seed=cfg.seed + g,
            strict=cfg.loop.strict_ratio)

        tok2 = load_tokenizer(base, cfg.model.trust_remote_code)
        # Gold (real) prompts are rendered here, so fit them into the training
        # window the same way generation prompts were fitted into theirs.
        fit_len = cfg.train.max_len - cfg.gen.max_new_tokens
        syn_pairs = build_pairs(syn_sel, {r["uid"]: r["response"] for r in syn_sel},
                                tok2, style=cfg.gen.prompt_style, max_len=fit_len)
        real_pairs = build_pairs(real_sel, None, tok2, style=cfg.gen.prompt_style,
                                 max_len=fit_len)
        pairs = syn_pairs + real_pairs
        del tok2

        # Where generation g+1 starts from. With chain="weights" this is model_g
        # itself, so degradation compounds; with chain="data_only" it is always
        # the pristine base and only the DATA carries the recursion forward.
        if cfg.loop.chain == "weights":
            init_base, init_adapter = base, adapter
            merge_before_save = (cfg.train.mode == "lora")
        elif cfg.loop.chain == "data_only":
            init_base, init_adapter = cfg.model.name, None
            merge_before_save = False
        else:
            raise ValueError(
                f"loop.chain must be 'weights' or 'data_only', got {cfg.loop.chain!r}")

        stats = train_sft(cfg, pairs, out_dir=ck, base_model=init_base,
                          init_adapter=init_adapter,
                          merge_before_save=merge_before_save)

        info = {"code_fingerprint": code_fingerprint(),
                "generation_from": g, "generation_to": g + 1,
                "chain": cfg.loop.chain, "init_from": str(init_base),
                "filter_quality": fq, "mix": mix_info,
                "self_target_entropy": self_target_entropy,
                "sampler": cfg.gen.sampler,
                "samples_per_prompt": cfg.loop.samples_per_prompt,
                "sampler_T_mean": (graded[-1].get("sampler_T_mean") if graded else None),
                "real_fresh_slice": list(fresh_slice) if fresh_slice else None,
                "n_syn_pairs": len(syn_pairs), "n_real_pairs": len(real_pairs),
                "train": {k: v for k, v in stats.items() if k != "history"},
                "train_history": stats.get("history", [])}
        write_json(ck / "_done.json", info)

        # Storage discipline: keep only the newest weights unless asked otherwise.
        if not cfg.loop.keep_checkpoints and g >= 1:
            prune_checkpoint(self.ckpt_dir(g))
        return info

    # ------------------------------------------------------------------- main
    def run(self) -> dict:
        pools = self.prepare()
        all_metrics = []
        gens = list(range(self.cfg.loop.generations))
        outer = pbar(total=len(gens), desc="generations", unit="gen", leave=True)
        for g in gens:
            m = self.evaluate_generation(g, pools)
            all_metrics.append(m)
            if g < self.cfg.loop.generations - 1:
                self.train_next(g, pools)
            outer.update(1)
        outer.close()

        summary = summarize(all_metrics)
        write_json(self.run_dir / "summary.json",
                   {"config_run": self.cfg.run_name, "metrics": all_metrics,
                    "summary": summary})
        LOG.info("run complete -> %s", self.run_dir / "summary.json")
        return summary


def _fmt_sig(entry: dict) -> str:
    sig = entry.get("signals", {})
    parts = []
    for name in ("mean_token_prob", "marker_conf", "p_correct"):
        if name in sig:
            parts.append(f"{name}: ece {sig[name]['ece']:.3f} "
                         f"auroc {sig[name]['auroc']:.3f} "
                         f"over {sig[name]['overconfidence']:+.3f}")
    return " | ".join(parts) if parts else "no signals"


def summarize(all_metrics: list[dict]) -> dict:
    """Per-eval-set trajectories, ready for the onset analysis."""
    out: dict = {"generations": [m["generation"] for m in all_metrics], "curves": {}}
    names = set()
    for m in all_metrics:
        names.update(m.get("eval", {}).keys())

    for name in sorted(names):
        curve: dict[str, list] = {
            "accuracy": [], "accuracy_generated": [], "accuracy_scored": [],
            "format_gap": [], "hedge_rate": [], "refusal_rate": [],
            "ece_internal": [], "ece_marker": [],
            "auroc_internal": [], "auroc_marker": [], "overconf_internal": [],
            "overconf_marker": [], "probe_auroc": [], "ivd_l1": [],
            "ivd_auroc_gap": [], "distinct_2": [], "vocab_size": [], "self_bleu": [],
        }
        for m in all_metrics:
            e = m.get("eval", {}).get(name)
            if e is None:
                for k in curve:
                    curve[k].append(None)
                continue
            sig = e.get("signals", {})
            internal = (sig.get("p_pred") or sig.get("mean_token_prob") or {})
            marker = sig.get("marker_conf", {})
            div = e.get("diversity", {})
            curve["accuracy"].append(e.get("accuracy"))
            curve["accuracy_generated"].append(e.get("accuracy_generated"))
            curve["accuracy_scored"].append(e.get("accuracy_scored"))
            curve["format_gap"].append(e.get("format_gap"))
            curve["hedge_rate"].append(e.get("hedge_rate"))
            curve["refusal_rate"].append(e.get("refusal_rate"))
            curve["ece_internal"].append(internal.get("ece"))
            curve["ece_marker"].append(marker.get("ece"))
            curve["auroc_internal"].append(internal.get("auroc"))
            curve["auroc_marker"].append(marker.get("auroc"))
            curve["overconf_internal"].append(internal.get("overconfidence"))
            curve["overconf_marker"].append(marker.get("overconfidence"))
            curve["probe_auroc"].append((e.get("probe") or {}).get("best_auroc"))
            curve["ivd_l1"].append((e.get("ivd") or {}).get("ivd_l1"))
            curve["ivd_auroc_gap"].append((e.get("ivd") or {}).get("ivd_auroc_gap"))
            curve["distinct_2"].append(div.get("distinct_2"))
            curve["vocab_size"].append(div.get("vocab_size"))
            curve["self_bleu"].append(div.get("self_bleu"))
        out["curves"][name] = curve
    return out
